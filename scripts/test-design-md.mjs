const UNKNOWN_FIXTURE = `# Some Random Doc

Just prose with a couple of headings.

## Notes

- nothing structured here
`;

// ----------------------------------------------------------------- detection

console.log("\n\x1b[1mformat detection\x1b[0m");
check(detectDesignMdFormat(REFERO_FIXTURE) === "refero", "frontmatter detected as refero");
check(detectDesignMdFormat(OD_B_FIXTURE) === "opendesign", "numbered skeleton detected as opendesign");
check(detectDesignMdFormat(OD_A_FIXTURE) === "opendesign", "family A detected as opendesign");
check(detectDesignMdFormat(UNKNOWN_FIXTURE) === "unknown", "plain prose detected as unknown");
check(detectDesignMdFormat("") === "unknown", "empty string detected as unknown");
check(detectDesignMdFormat(undefined) === "unknown", "undefined input does not throw");

// ------------------------------------------------------------------- refero

console.log("\n\x1b[1mrefero fixture\x1b[0m");
const ref = parseDesignMd(REFERO_FIXTURE);
check(ref.format === "refero", "format is refero");
check(ref.name === "Example App", `name from frontmatter (${ref.name})`);
check(ref.northStar === "A calm workspace with one electric accent and quiet neutral layers.", "north star from blockquote");
check(ref.frontmatter?.theme === "light" && ref.frontmatter?.industry === "saas", "frontmatter scalars parsed");
check(Array.isArray(ref.frontmatter?.tags) && ref.frontmatter.tags[1] === "dark-code", "tags flow-list parsed");
check(ref.colors.length === 4, `colors table parsed, invalid hex skipped (${ref.colors.length})`);
check(ref.colors[2].hex === "#1b55f5" && ref.colors[2].group === "brand", "hex unbackticked and group lowered");
check(ref.colors[3].group === "semantic", "semantic group preserved");
check(ref.fonts.length === 2 && ref.fonts[0] === "Poppins", "fonts parsed");
check(ref.do.length === 2 && ref.dont.length === 1, "do/don't bullets parsed");
check(!JSON.stringify(ref.do).includes("Generated by"), "footer excluded from sections");

// A refero doc with industry missing and no Don't section.
const refMinimal = parseDesignMd(
  REFERO_FIXTURE.replace("industry: saas\n", "").replace(/## Don't[\s\S]*$/, ""),
);
check(refMinimal.frontmatter.industry === undefined, "missing industry tolerated");
check(refMinimal.dont.length === 0 && refMinimal.do.length === 2, "missing Don't section tolerated");

// --------------------------------------------------------- opendesign B

console.log("\n\x1b[1mopendesign family B fixture\x1b[0m");
const odb = parseDesignMd(OD_B_FIXTURE);
check(odb.format === "opendesign" && odb.colorFamily === "b", "detected as opendesign family B");
check(odb.name === "Agentic", `name stripped of the boilerplate prefix (${odb.name})`);
check(odb.colors.length === 4, `role lines parsed, invalid value skipped (${odb.colors.length})`);
const roles = odb.colors.map((c) => c.role);
check(roles.includes("Primary") && roles.includes("Text") && roles.includes("Surface"), "canonical roles captured");
check(odb.colors[0].hex === "#FF5701", "hex unbackticked");
check(odb.typography?.scale.length === 6 && odb.typography.scale[0] === "14px", `typography scale parsed (${odb.typography?.scale.join(",")})`);
check(odb.typography?.families.primary === "Playfair Display" && odb.typography.families.mono === "JetBrains Mono", "families k=v pairs parsed");
check(odb.typography?.weights.join(",") === "100,400,700", "weights CSV parsed");
check(odb.antiPatterns.length === 2, "anti-patterns parsed");
check(odb.do.length === 0 && odb.dont.length === 0, "no Do/Don't sections in family B");
check(Object.keys(odb.sections).length === 9, `all 9 sections captured (${Object.keys(odb.sections).length})`);
check(JSON.stringify(odb.sections).includes("minimal"), "sections serialize as a plain object (JSON-safe)");

// --------------------------------------------------------- opendesign A

console.log("\n\x1b[1mopendesign family A fixture\x1b[0m");
const oda = parseDesignMd(OD_A_FIXTURE);
check(oda.format === "opendesign" && oda.colorFamily === "a", "detected as opendesign family A");
check(oda.colors.length === 4, `### subsection token lines parsed (${oda.colors.length})`);
check(oda.colors[0].name === "Ink" && oda.colors[0].group === "primary", "name + subsection group captured");
check(oda.colors[2].name === "Paper" && oda.colors[2].group === "neutrals & text", "second subsection group captured");
check(oda.do.length === 1 && oda.dont.length === 1, "Do's/Don'ts H3 halves parsed");
check(oda.typography === null, "prose typography yields null, not an empty object");

// ------------------------------------------------------------- unknown

console.log("\n\x1b[1munknown fixture\x1b[0m");
const unk = parseDesignMd(UNKNOWN_FIXTURE);
check(unk.format === "unknown" && unk.name === "Some Random Doc", "unknown doc keeps title");
check(unk.colors.length === 0 && unk.do.length === 0, "unknown doc extracts nothing structured");
check(unk.sections["Notes"].includes("nothing structured"), "unknown doc keeps section bodies");

// -------------------------------------------------- manifest projection

console.log("\n\x1b[1mmanifestFromDesignMd\x1b[0m");
const mf = manifestFromDesignMd(odb);
check(mf.schemaVersion === "design-system-manifest/v1", "schema version carried");
check(mf.name === "Agentic" && mf.slug === "agentic", "name and slug set");
check(mf.overview.principles.length === 0 && mf.overview.antiPatterns.length === 2, "anti-patterns land in overview");
check(mf.colors.swatches.length === 4 && mf.colors.ramps && Object.keys(mf.colors.ramps.neutral).length === 0, "swatches filled, ramps left empty");
check(mf.typography.list.length === 3 && mf.typography.scale.length === 6, "typography list and scale carried");
check(mf.provenance?.format === "opendesign" && mf.provenance.filled.includes("colors.swatches"), "provenance marks filled fields");
check(mf.provenance.open.includes("colors.roles") && mf.provenance.open.includes("spacing.scale"), "provenance names open fields");
check(!mf.$comment && !mf.overview.$comment, "template $comment docs stripped from the projection");

const mfRef = manifestFromDesignMd(ref);
check(mfRef.overview.principles.length === 2 && mfRef.overview.antiPatterns.length === 1, "refero do/don't map to principles/anti-patterns");
check(mfRef.theme.params.parsedFrom === "design-md" && mfRef.theme.params.format === "refero", "theme.params records the source format");

const mfEnriched = manifestFromDesignMd(combineTokens(unk, [
  { name: "--bg", value: "#ffffff", type: "color" },
  { name: "--space-2", value: "8px", type: "dimension" },
  { name: "--text-md", value: "16px", type: "dimension" },
  { name: "--radius-sm", value: "6px", type: "dimension" },
  { name: "--tracking-display", value: "-0.02em", type: "dimension" },
  { name: "--shadow-md", value: "0 2px 8px rgba(0,0,0,.2)", type: "shadow" },
  { name: "--font-body", value: "Inter, sans-serif", type: "fontFamily" },
]));
check(mfEnriched.provenance.enriched === true, "enrichment flag set");
check(mfEnriched.colors.swatches[0].name === "bg", "token colors fill swatches when the doc states none");
check(mfEnriched.spacing.scale.length === 1 && mfEnriched.spacing.scale[0].token === "--space-2", "only spacing tokens go in the spacing scale");
check(mfEnriched.radius.sm === "6px" && mfEnriched.shadows.tokens.length === 1, "radius and shadows carry over");
check(!mfEnriched.provenance.open.includes("radius.sm"), "provenance tracks radius independently");
check(mfEnriched.typography.body.family === "Inter, sans-serif" && mfEnriched.typography.scale[0] === "16px", "sidecar fonts and font sizes carry over");
check(mfEnriched.provenance.filled.some((f) => f.includes("token payload")), "provenance credits the token payload");

const conflict = combineTokens(odb, [
  { name: "--primary", value: "#ffffff", type: "color" },
  { name: "--focus", value: "#222222", type: "color" },
]);
check(conflict.tokens.find((t) => t.path === "colors.primary").value === "#FF5701", "declared values take precedence at the same path");
check(conflict.diagnostics.some((d) => d.code === "token-conflict"), "companion color conflicts are reported");
check(manifestFromDesignMd(conflict).colors.swatches.some((c) => c.name === "focus"), "companion colors fill additional swatches");

console.log("\n\x1b[1mreal document variations\x1b[0m");
const rules = parseDesignMd(`# Brand

## 7. Do’s and Don’ts
### \u2705 Do
- Keep the canvas light.
### \u274c Don’t
- Use dark fills.

## Do not
- Add decorative shadows.

## Anti-patterns
- Ghost buttons on photos.
`);
check(rules.do.length === 1 && rules.dont.length === 2, "decorated headings and Do not preserve rule polarity");
check(manifestFromDesignMd(rules).overview.antiPatterns.length === 3, "both prohibitions and anti-patterns are carried");
const bareRules = parseDesignMd("## Do's and Don'ts\n\n- Do not use gradients.\n- **Do** use the primary color sparingly.\n");
check(bareRules.do.length === 1 && bareRules.dont.length === 1, "inline Do and Do not in a mixed section keep their polarity");

const roundTripRefero = parseDesignMd([
  "---",
  "site_name: 'R&D: Product'",
  'tags: ["design, art", developer-tools]',
  "---",
  "# R&D: Product",
  "",
  "> First paragraph.",
  ">",
  "> Second paragraph.",
  "",
  "## Colors",
  "Hex | Name | Role | Group",
  "--- | --- | --- | ---",
  "`#abcdef` | Primary \\| Strong | Main action | Brand",
  "",
  "## Tags",
  "`design, art` · `developer-tools`",
  "",
  "## Usage",
  "```md",
  "## 1. Fake Heading",
  "- Don't extract this.",
  "```",
  "",
  "## Usage",
  "More prose.",
].join("\n"));
check(roundTripRefero.tags.length === 2 && roundTripRefero.tags[0] === "design, art", "Refero keeps quoted tags and their count");
check(roundTripRefero.colors[0]?.name === "Primary | Strong" && roundTripRefero.colors[0]?.role === "Main action", "escaped table cells keep their column");
check(roundTripRefero.northStar.includes("Second paragraph."), "quoted paragraphs remain available");
check(!roundTripRefero.sections["1. Fake Heading"] && roundTripRefero.sections.Usage.includes("More prose"), "fenced headings are ignored and repeated sections retain both bodies");
check(roundTripRefero.diagnostics.some((d) => d.code === "duplicate-heading"), "duplicate headings produce a diagnostic");
check(Object.getPrototypeOf(parseDesignMd("").sections) === Object.prototype, "empty sections use the same JSON shape");

console.log("\n\x1b[1mexternal formats and authoring\x1b[0m");
const draft = renderDesignMdDraft({
  name: "Daylight Prestige",
  tokens: {
    colors: { primary: "#1a1c1e", action: "{colors.primary}" },
    typography: { body: { fontFamily: "Public Sans, sans-serif", fontSize: "1rem", fontWeight: 500 } },
    components: { button: { backgroundColor: "{colors.action}", typography: "{typography.body}" } },
  },
  body: "## Layout\n\n```yaml\nspacing:\n  gutter: 24px\n```\n",
});
const stitch = parseDesignMd(draft);
check(stitch.format === "stitch" && stitch.name === "Daylight Prestige" && !stitch.diagnostics.length, "generated Stitch file imports cleanly");
check(stitch.tokens.find((t) => t.path === "components.button.backgroundColor").value === "#1a1c1e", "resolves chained references");
check(stitch.tokens.find((t) => t.path === "components.button.typography").value.fontWeight === 500, "resolves composite component references");
check(stitch.tokens.find((t) => t.path === "components.button.typography.fontFamily").value === "Public Sans, sans-serif", "composite component fields have their own checkable paths");
check(stitch.tokens.find((t) => t.path === "spacing.gutter").source === "yaml-block", "interleaved YAML contributes tokens");
const invalid = parseDesignMd(draft + "\n```yaml\ncolors: { new: red }\n```\n");
check(invalid.diagnostics.some((d) => d.code === "duplicate-token-group"), "duplicate token groups are surfaced");
const invalidRefs = parseDesignMd('---\nversion: alpha\ncolors: { a: "{colors.b}", b: "{colors.a}", c: "{colors.missing}" }\n---\n');
check(invalidRefs.diagnostics.some((d) => d.code === "cyclic-token-reference") && invalidRefs.diagnostics.some((d) => d.code === "unknown-token-reference"), "cyclic and missing token references are surfaced");

const hot = parseDesignMd(`---
name: WebDesignHot example
source_url: https://example.test
spec: webdesignhot/0.2
colors:
  light: { bg: "#fff" }
  dark: { bg: "#000" }
themes: { default: dark }
aliases: { background: bg }
typography:
  body: { family: Inter, weights: [400, 700] }
  scale:
    display-hero: { size: 4rem, weight: 700, family: Inter }
---
## 1. Visual Theme & Atmosphere
`);
check(hot.format === "webdesignhot" && hot.colors.length === 2 && hot.fonts[0] === "Inter", "detects WebDesignHot with source_url and preserves named themes");
check(manifestFromDesignMd(hot).colors.roles.bg === "#000", "manifest uses the declared default theme");
check(hot.typography.scale[0] === "4rem" && hot.typography.weights.join(",") === "400,700", "WebDesignHot nested type scales and weights remain structured");
check(ref.tokens.some((token) => token.path === "typography.unassigned.poppins.fontFamily"), "unassigned Refero fonts have checkable token paths");
const css = readCssTokens(`
  :root { --bg: oklch(98.75% 0 0); --fg: #222; --muted: var(--fg); --space-2: 8px; }
  @media (prefers-color-scheme: dark) { :root { --bg: black; } }
  [data-theme="dark"] { --bg: black; }
`);
check(css.find((t) => t.name === "--bg")?.value === "oklch(98.75% 0 0)" && css.find((t) => t.name === "--muted")?.value === "#222", "CSS companion reads the base root and simple aliases");

const report = validateDesignObservations(stitch, [
  { location: "button", token: "components.button.backgroundColor", value: "rgb(26, 28, 30)" },
  { location: "main", token: "typography.body.fontSize", value: "16px", rootFontSize: 16 },
  { location: "main", token: "typography.body.fontFamily", value: '"Public Sans",sans-serif' },
  { location: "main", token: "spacing.gutter", value: "32px" },
  { location: "footer", token: "spacing.gutter", value: null },
  { location: "footer", token: "colors.missing", value: "red" },
]);
check(report.documentValid && !report.conforms && report.summary.pass === 3 && report.summary.fail === 1 && report.summary.unverified === 2, "validates effective values and reports missing evidence distinctly");
check(!validateDesignObservations(stitch, []).conforms, "zero observations do not establish conformance");

const partial = [{ location: "button", token: "colors.primary", value: "#1a1c1e" }];
const covered = validateDesignObservations(stitch, partial, ["colors.primary", "spacing.gutter", "colors.unknown"]);
check(validateDesignObservations(stitch, partial).conforms && !covered.conforms && covered.coverage.pass === 1 &&
  covered.coverage.missing === 1 && covered.coverage.unverified === 1, "required coverage catches unsampled and unknown tokens");
const mismatch = validateDesignObservations(stitch, [...partial,
  { location: "footer", token: "colors.primary", value: null },
  { location: "hover", token: "colors.primary", value: "#ffffff" },
], ["colors.primary"]);
check(mismatch.coverage.fail === 1 && !mismatch.conforms, "a mismatch takes precedence over other observations for the same role");
check(validateDesignObservations(stitch, partial, ["colors.primary"]).conforms, "a fully checked required scope conforms");

const pkg = await mkdtemp(join(tmpdir(), "designer-package-"));
const builder = fileURLToPath(new URL("../skills/designer-mcp/scripts/build-design-system.mjs", import.meta.url));
const runBuilder = (...args) => spawnSync(process.execPath, [builder, pkg, ...args], { encoding: "utf8" });
try {
  await mkdir(join(pkg, "templates", "landing"), { recursive: true });
  await writeFile(join(pkg, "templates", "landing", "index.html"), '<link rel="stylesheet" href="../../styles.css">');
  await writeFile(join(pkg, "recipes.css"), "button { background: var(--component-button-background-color); }");
  await writeFile(join(pkg, "theme.json"), JSON.stringify({
    version: 1,
    name: "Daylight Prestige",
    tokens: stitch.tokens,
    templates: [{ name: "Landing", entryPath: "templates/landing/index.html" }],
  }));
  const build = runBuilder();
  check(build.status === 0, `builds a package from the same normalized token rows${build.status ? ` (${build.stderr.trim()})` : ""}`);
  if (build.status === 0) {
    const css = await readFile(join(pkg, "styles.css"), "utf8");
    const manifest = JSON.parse(await readFile(join(pkg, "_ds_manifest.json"), "utf8"));
    const copiedBuilder = join(pkg, "scripts", "build-design-system.mjs");
    check(css.includes("--component-button-background-color: var(--color-action);") &&
      css.includes("--component-button-typography-font-family: var(--font-body);") &&
      css.includes("button { background: var(--component-button-background-color); }") &&
      manifest.templates[0]?.folder === "templates/landing" &&
      spawnSync(process.execPath, [copiedBuilder, pkg, "--check"]).status === 0,
      "package preserves aliases and recipes and verifies byte-for-byte using its bundled builder");
    await writeFile(join(pkg, "styles.css"), css + "\n/* drift */\n");
    check(runBuilder("--check").status !== 0, "package check reports generated file drift");
  }
} finally {
  await rm(pkg, { recursive: true, force: true });
}

// ------------------------------------------------------------------ done

console.log(
  failures === 0
    ? `\n\x1b[32m\x1b[1mAll design-md parser tests passed.\x1b[0m\n`
    : `\n\x1b[31m\x1b[1m${failures} design-md parser test(s) failed.\x1b[0m\n`,
);
process.exit(failures === 0 ? 0 : 1);
