#!/usr/bin/env node
/**
 * Unit tests for scripts/lib/design-md-parse.mjs — fixture-driven and
 * cache-independent, so they run anywhere (no catalog needed).
 *
 * Exercises catalog Markdown, external structured formats, companion tokens,
 * manifest projection, and author/validate round trips.
 *
 * Usage: node scripts/test-design-md.mjs
 */

import { spawnSync } from "node:child_process";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { parseDesignMd, detectDesignMdFormat, manifestFromDesignMd } from "./lib/design-md-parse.mjs";
import { combineTokens, readCssTokens, renderDesignMdDraft, validateDesignObservations } from "./lib/design-md-tokens.mjs";

let failures = 0;
const ok = (msg) => console.log(`  \x1b[32m✓\x1b[0m ${msg}`);
const bad = (msg) => {
  failures++;
  console.log(`  \x1b[31m✗\x1b[0m ${msg}`);
};
const check = (cond, msg) => (cond ? ok(msg) : bad(msg));

// ------------------------------------------------------------------ fixtures

