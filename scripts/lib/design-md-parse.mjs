/** Normalize catalog and external DESIGN.md files without I/O. */
import MarkdownIt from "markdown-it";
import { blankManifestTemplate, MANIFEST_SCHEMA_VERSION } from "./ds-manifest.mjs";
import { isColorValue, nameKey, readYaml, structuredFormat, structuredTokens } from "./design-md-tokens.mjs";

const markdown = new MarkdownIt({ html: true });
const HEX_RE = /^#(?:[0-9a-f]{3}|[0-9a-f]{4}|[0-9a-f]{6}|[0-9a-f]{8})$/i;
const bareHeading = (text) => text.replace(/^\d+[.)]\s+/, "").trim();

function splitDocument(input) {
  const text = input.replace(/^\uFEFF/, "").replace(/\r\n?/g, "\n");
  const lines = text.split("\n");
  const diagnostics = [];
  let start = 0;
  let frontmatter = null;
  if (lines[0] === "---") {
    const end = lines.indexOf("---", 1);
    if (end < 0) {
      diagnostics.push({ severity: "error", code: "unclosed-frontmatter", line: 1 });
    } else {
      const raw = lines.slice(1, end).join("\n");
      let yaml = raw;
      // The upstream Refero renderer leaves a trailing colon in a site name unquoted.
      if (/^source_url:/m.test(raw) && /^extracted_at:/m.test(raw)) {
        yaml = raw.replace(/^(site_name:[ \t]+)([^"'\n][^\n]*:)[ \t]*$/m, (_, prefix, value) =>
          prefix + JSON.stringify(value));
        if (yaml !== raw) {
          const line = lines.findIndex((text) => text.startsWith("site_name:")) + 1;
          diagnostics.push({ severity: "warning", code: "repaired-refero-frontmatter", line });
        }
      }
      frontmatter = readYaml(yaml, 2, diagnostics);
      start = end + 1;
    }
  }

  const body = lines.slice(start).join("\n");
  const prose = lines.slice(start);
  const blocks = [];
  const headings = [];
  let title = "";
  const tokens = markdown.parse(body, {});
  for (const token of tokens) {
    if (token.level !== 0) continue;
    if (["fence", "code_block", "html_block"].includes(token.type)) {
      const [first, end] = token.map;
      if (token.type === "fence" && /^ya?ml$/i.test(token.info.trim())) {
        const line = start + first + 2;
        blocks.push({ value: readYaml(token.content, line, diagnostics), source: "yaml-block", line });
      }
      prose.fill("", first, end);
    }
  }

  let footer = prose.length;
  for (const [index, token] of tokens.entries()) {
    if (token.level !== 0) continue;
    if (token.type === "hr") {
      const after = prose.slice(token.map[1]).join("\n").trim();
      if (/^Generated by refero-mcp from [^\n]+$/.test(after)) footer = token.map[0];
    }
    if (token.type !== "heading_open") continue;
    const heading = tokens[index + 1].content.trim();
    if (token.tag === "h1" && !title && !headings.length) title = heading;
    if (token.tag === "h2") headings.push({ heading, line: token.map[0], end: token.map[1] });
  }

  const sections = new Map();
  const sourceSections = new Map();
  for (const [index, { heading, line, end }] of headings.entries()) {
    const stop = Math.min(headings[index + 1]?.line ?? footer, footer);
    if (sections.has(heading)) diagnostics.push({ severity: "error", code: "duplicate-heading", line: start + line + 1, heading });
    const add = (map, value) => map.set(heading, [map.get(heading), value.trim()].filter(Boolean).join("\n\n"));
    add(sections, prose.slice(end, stop).join("\n"));
    add(sourceSections, lines.slice(start + end, start + stop).join("\n"));
  }
  const intro = prose.slice(0, headings[0]?.line ?? footer).join("\n");
  return { title, frontmatter, blocks, sections, sourceSections, intro, diagnostics, body: lines.slice(start, start + footer).join("\n").trim() };
}

/** The first top-level quote before the document's sections. */
function firstBlockquote(text) {
  const lines = [];
  for (const line of text.split("\n")) {
    const match = line.match(/^>\s?(.*)$/);
    if (match) lines.push(match[1].trim());
    else if (lines.length) break;
  }
  return lines.join("\n").trim();
}

function bullets(body) {
  const lines = (body ?? "").split("\n");
  const list = markdown.parse(body ?? "", {});
  return list.filter((token) => token.type === "list_item_open" && token.level === 1)
    .map(({ map: [start, end] }) => lines.slice(start, end).join("\n").replace(/^\s*(?:[-+*]|\d+[.)])\s+/, "").trim());
}

function tables(body) {
  const list = markdown.parse(body, {});
  const result = [];
  let table;
  let row;
  for (const token of list) {
    if (token.type === "table_open") table = { line: token.map[0], rows: [] };
    if (token.type === "table_close") {
      result.push(table);
      table = null;
    }
    if (!table) continue;
    if (token.type === "tr_open") row = [];
    if (token.type === "inline") row.push(token.content);
    if (token.type === "tr_close") table.rows.push(row);
  }
  return result;
}

function findSection(sections, pattern) {
  for (const [heading, body] of sections) {
    if (pattern.test(bareHeading(heading))) return { heading, body };
  }
  return null;
}

function stripBackticks(value) {
  return String(value || "").replace(/^`+|`+$/g, "").trim();
}

function parseRefero({ frontmatter, title, sections, intro }) {
  const colors = [];
  const colorSection = findSection(sections, /^colors?\b/i);
  for (const table of tables(colorSection?.body ?? "")) {
    for (const [value, name = "", role = "", group = ""] of table.rows.slice(1)) {
      const hex = stripBackticks(value);
      if (HEX_RE.test(hex)) colors.push({ hex, name, role, group: group.toLowerCase() });
    }
  }
  const tagsSection = findSection(sections, /^tags?\b/i);
  const inlineTags = markdown.parseInline(tagsSection?.body ?? "", {})[0].children
    .filter((token) => token.type === "code_inline").map((token) => token.content);
  const tags = Array.isArray(frontmatter?.tags) ? frontmatter.tags : inlineTags;
  return {
    format: "refero",
    name: frontmatter?.site_name || title,
    northStar: firstBlockquote(intro),
    colors,
    fonts: bullets(findSection(sections, /^fonts?\b/i)?.body),
    ...parseRules(sections),
    typography: null,
    tags,
  };
}

const NOISE_CELL_RE = /^(:N?A:?|[\d.]+\s*:\s*[\d.]+:?|\d+(?:\.\d+)?%?|\u2705.*|AA\(?.*|AAA.*)$/i;

/**
 * Colors from a markdown table whose header carries a Hex column. OpenDesign
 * family-A documents embed `| Token | Hex | Role |`-shaped tables (column
 * count varies: 3-6, sometimes with Name and WCAG columns).
 */
function tableColorRows([header, ...rows], fallbackGroup) {
  const hexIdx = header.findIndex((h) => /^(?:hex|value)$/i.test(stripBackticks(h)));
  if (hexIdx < 0) return [];
  const nameIdx = header.findIndex((h, i) => i !== hexIdx && /^(token|color|name|swatch|role)/i.test(h));
  const out = [];
  for (const cells of rows) {
    const hex = stripBackticks(cells[hexIdx]);
    if (!isColorValue(hex)) continue;
    const name = nameIdx >= 0 ? stripBackticks(cells[nameIdx]) : "";
    const role = cells
      .filter((c, i) => i !== hexIdx && i !== nameIdx && c && !NOISE_CELL_RE.test(stripBackticks(c)))
      .map((c) => stripBackticks(c).replace(/^\*\*|\*\*$/g, ""))
      .join(" - ");
    out.push({ hex, name: name || fallbackGroup || "", role, group: fallbackGroup.toLowerCase() });
  }
  return out;
}

/** Family B color line: `- **Role:** `#HEX` — description` */
function odRoleLine(line) {
  const m = line.match(/^\s*[-*+]\s+\*\*([^*]+?):?\*\*:?\s*(.+)$/);
  if (!m) return null;
  const role = m[1].trim();
  let rest = m[2].trim();
  let value = "";
  const bt = rest.match(/^`([^`]+)`/);
  if (bt) {
    value = bt[1].trim();
    rest = rest.slice(bt[0].length);
  } else {
    const bare = rest.match(/^(\S+)/);
    if (bare) {
      value = bare[1];
      rest = rest.slice(bare[0].length);
    }
  }
  const desc = rest.replace(/^[—–-]+\s*/, "").trim();
  if (!isColorValue(value)) return null;
  return { role, hex: value, name: role, description: desc };
}

/** Family A token line: `- **Name** (`#hex`): description` */
function odTokenLine(line) {
  const m = line.match(/^\s*(?:[-*+]\s+)?\*\*([^*]+)\*\*\s*\((.+?)\):\s*(.*)$/)
    ?? line.match(/^\s*[-*+]\s+\*\*(.+?)\s+\((.+?)\):?\*\*:?\s*(.*)$/);
  if (!m) return null;
  const value = stripBackticks(m[2]);
  if (!isColorValue(value)) return null;
  return { name: m[1].trim(), hex: value, description: m[3].trim() };
}

/** `**Scale:** 14/16/18/24` -> ["14px", ...]; `**Families:** primary=X` -> {primary:X}; `**Weights:**` CSV. */
function odTypography(body) {
  const out = { scale: [], families: {}, weights: [] };
  const families = new Map();
  for (const line of (body || "").split("\n")) {
    let m = line.match(/\*\*Scale:?\*\*:?\s*(.+)$/i);
    if (m) {
      out.scale = m[1]
        .split(/[\s/]+/)
        .map((v) => stripBackticks(v).replace(/,$/, ""))
        .filter((v) => /^\d+(?:\.\d+)?(?:px|pt|rem|em|%)?$/.test(v))
        .map((v) => (/^\d+(?:\.\d+)?$/.test(v) ? `${v}px` : v));
      continue;
    }
    m = line.match(/\*\*Families:?\*\*:?\s*(.+)$/i);
    if (m) {
      for (const pair of m[1].split(",")) {
        const kv = pair.split("=");
        if (kv.length === 2) families.set(kv[0].trim(), kv[1].trim());
      }
      continue;
    }
    m = line.match(/\*\*Weights:?\*\*:?\s*(.+)$/i);
    if (m) {
      out.weights = m[1].split(/[,\s]+/).map((w) => w.trim()).filter(Boolean);
    }
  }
  out.families = Object.fromEntries(families);
  return out.scale.length || families.size || out.weights.length ? out : null;
}

const normalizeRule = (text) => text.replace(/^[^\p{L}]+/u, "").replace(/[’‘]/g, "'").replace(/\*/g, "").toLowerCase();
const combinedRules = /^(?:do'?s?)(?:\s+and\s+|\s*[/&]\s*)don'?ts?\b/;
const negativeRule = /^(?:don'?ts?|do not|avoid|never|must not|should not|no)\b/;
const positiveRule = /^do(?:'s|s)?\b/;

function parseRules(sections) {
  const rules = { do: [], dont: [], antiPatterns: [] };
  function add(body, bucket) {
    for (const bullet of bullets(body)) {
      const rule = normalizeRule(bullet);
      let target = bucket;
      if (bucket !== "antiPatterns" && negativeRule.test(rule)) target = "dont";
      if (!target && positiveRule.test(rule)) target = "do";
      if (target) rules[target].push(bullet);
    }
  }

  for (const [heading, body] of sections) {
    const label = normalizeRule(bareHeading(heading));
    if (combinedRules.test(label)) {
      const lines = body.split("\n");
      let bucket = null;
      let start = 0;
      const tokens = markdown.parse(body, {});
      for (const [index, token] of tokens.entries()) {
        if (token.level !== 0 || token.type !== "heading_open") continue;
        add(lines.slice(start, token.map[0]).join("\n"), bucket);
        const sub = normalizeRule(tokens[index + 1].content);
        bucket = negativeRule.test(sub) ? "dont" : positiveRule.test(sub) ? "do" : null;
        start = token.map[1];
      }
      add(lines.slice(start).join("\n"), bucket);
    } else if (/anti[ -]?patterns?|usage guardrails/.test(label)) {
      add(body, "antiPatterns");
    } else if (negativeRule.test(label)) {
      add(body, "dont");
    } else if (positiveRule.test(label)) {
      add(body, "do");
    }
  }
  return rules;
}

function proseDesign({ title, sections, intro }, format) {
  const colors = [];
  const colorSection = findSection(sections, /^(?:colou?r|palette)\b|^colou?rs\b/i);
  let colorFamily = null;
  if (colorSection) {
    let group = "";
    const tableByLine = new Map(tables(colorSection.body).map((table) => [table.line, table.rows]));
    for (const [index, line] of colorSection.body.split("\n").entries()) {
      const h3 = line.match(/^ {0,3}###\s+(.+)$/);
      if (h3) group = h3[1].replace(/\s*\(.*?\)\s*$/, "").trim();
      if (tableByLine.has(index)) {
        const rows = tableColorRows(tableByLine.get(index), group);
        if (rows.length) colorFamily ||= "table";
        colors.push(...rows);
      }
      const token = odTokenLine(line);
      if (token) {
        colorFamily ||= "a";
        colors.push({ hex: token.hex, name: token.name, role: token.description, group: group.toLowerCase() });
        continue;
      }
      const role = odRoleLine(line);
      if (role) {
        colorFamily ||= "b";
        colors.push({ hex: role.hex, name: role.name, role: role.role, group: group.toLowerCase(), description: role.description });
      }
    }
  }

  const typography = odTypography(findSection(sections, /typography/i)?.body);
  const fonts = [...Object.values(typography?.families ?? {}), ...bullets(findSection(sections, /^fonts?\b/i)?.body)];
  return {
    format,
    name: title.replace(/^Design System (Inspired )?by\s+/i, "").trim() || title,
    northStar: firstBlockquote(intro),
    colors,
    fonts,
    ...parseRules(sections),
    typography,
    tags: [],
    theme: findSection(sections, /visual theme|atmosphere|^overview$/i)?.body ?? "",
    colorFamily,
  };
}

