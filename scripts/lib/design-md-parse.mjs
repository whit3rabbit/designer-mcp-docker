const OD_VOCAB_RE = /visual theme|atmosphere|anti-?patterns?|agent prompt|color palette|component stylings|design system metadata/i;

function classify({ frontmatter, blocks, sections }, source) {
  const structured = structuredFormat(frontmatter, blocks);
  if (structured) return structured;
  if (source === "refero" || typeof frontmatter?.site_name === "string" ||
      (frontmatter?.source_url && frontmatter.extracted_at)) return "refero";
  if (source === "opendesign") return "opendesign";
  const headings = [...sections.keys()];
  const hasNumberedDesignSection = headings.some((heading) =>
    /^\d+[.)]\s+(?:colou?rs?\b|typography\b|layout\b|components?\b)/i.test(heading));
  if (hasNumberedDesignSection || headings.some((heading) => OD_VOCAB_RE.test(heading))) return "opendesign";
  return "unknown";
}

function proseTokens(parsed, diagnostics) {
  const values = new Map();
  const ambiguous = new Set();
  for (const { name, hex } of parsed.colors) {
    const key = nameKey(name);
    if (!key) continue;
    const path = `colors.${key}`;
    if (values.has(path) && values.get(path).value.toLowerCase() !== hex.toLowerCase()) {
      ambiguous.add(path);
    } else {
      values.set(path, { path, kind: "color", value: hex, source: "markdown" });
    }
  }
  for (const path of ambiguous) {
    values.delete(path);
    diagnostics.push({ severity: "warning", code: "ambiguous-prose-color", path });
  }
  for (const [name, value] of Object.entries(parsed.typography?.families ?? {})) {
    const key = nameKey(name);
    if (!key) continue;
    const path = `typography.${key}.fontFamily`;
    values.set(path, { path, kind: "font", value, source: "markdown" });
  }
  const assignedFonts = new Set(Object.values(parsed.typography?.families ?? {}));
  for (const value of parsed.fonts) {
    const key = nameKey(value);
    if (!key || assignedFonts.has(value)) continue;
    const path = `typography.unassigned.${key}.fontFamily`;
    values.set(path, { path, kind: "font", value, source: "markdown" });
  }
  return [...values.values()];
}

export function parseDesignMd(md, { source } = {}) {
  const doc = splitDocument(String(md ?? ""));
  const format = classify(doc, source);
  const parsed = format === "refero" ? parseRefero(doc) : proseDesign(doc, format);
  const { frontmatter, blocks, body, sourceSections, diagnostics } = doc;
  const normalized = {
    ...parsed,
    name: parsed.name || (typeof frontmatter?.name === "string" ? frontmatter.name : ""),
    frontmatter,
    body,
    sections: Object.fromEntries(sourceSections),
    diagnostics,
  };
  if (format === "stitch" || format === "webdesignhot") {
    if (typeof frontmatter?.name === "string") normalized.name = frontmatter.name;
    const { tokenTree, tokens } = structuredTokens(format, frontmatter, blocks, diagnostics);
    const colors = tokens.filter(({ path, kind }) => kind === "color" && path.startsWith("colors."));
    const fonts = tokens.filter(({ kind, path }) => kind === "font" && path.startsWith("typography."));
    const scales = tokens.filter(({ kind, path }) => kind === "fontSize" && path.startsWith("typography."));
    if (colors.length) normalized.colors = colors.map(({ path, value }) => ({
      hex: value, name: path.slice("colors.".length), role: "", group: "",
    }));
    if (fonts.length) normalized.fonts = [...new Set(fonts.map(({ value }) => value))];
    if (fonts.length || scales.length) normalized.typography = {
      scale: scales.map(({ value }) => value),
      families: Object.fromEntries(fonts.map(({ path, value }) => [path.split(".").slice(1, -1).join("."), value])),
      weights: [...new Set(tokens
        .filter(({ path }) => path.startsWith("typography.") && /\.(fontWeight|weights?)$/.test(path))
        .flatMap(({ value }) => value))],
    };
    return { ...normalized, tokenTree, tokens };
  }
  return { ...normalized, tokenTree: {}, tokens: proseTokens(parsed, diagnostics) };
}

export function detectDesignMdFormat(md) {
  return classify(splitDocument(String(md ?? "")));
}

/** Project the normalized document and sidecar tokens into the local manifest. */
export function manifestFromDesignMd(parsed) {
  const m = blankManifestTemplate();
  delete m.$comment;
  for (const value of Object.values(m)) {
    if (value && typeof value === "object") delete value.$comment;
  }

  const filled = [];
  const open = [];
  function record(path, present, source) {
    if (present) filled.push(source === "sidecar" ? `${path} (from token payload)` : path);
    else open.push(path);
  }
  const tokens = parsed.tokens;
  const sidecar = tokens.filter((token) => token.source === "sidecar");
  const grouped = (kind) => tokens.filter((token) => token.kind === kind);
  const tokenRows = (group) => group.map(({ name, path, value }) => ({ token: name ?? path, value }));
  const byPath = new Map(tokens.map((token) => [token.path, token]));

  m.name = parsed.name;
  m.slug = nameKey(parsed.name);
  m.description = typeof parsed.frontmatter?.description === "string"
    ? parsed.frontmatter.description : parsed.northStar || parsed.theme || "";
  m.overview.direction = parsed.northStar || parsed.theme || "";
  m.overview.principles = [...new Set(parsed.do)];
  m.overview.antiPatterns = [...new Set([...parsed.dont, ...parsed.antiPatterns])];
  record("overview.direction", m.overview.direction);
  record("overview.principles", m.overview.principles.length);
  record("overview.antiPatterns", m.overview.antiPatterns.length);
  open.push("overview.usingTokens", "overview.usingComponents", "overview.accessibility");

  const extraColors = sidecar.filter(({ kind }) => kind === "color");
  m.colors.swatches = [...parsed.colors, ...extraColors.map(({ path, value }) => ({
    name: path.slice("colors.".length), hex: value, role: "", group: "",
  }))];
  record("colors.swatches", m.colors.swatches.length, parsed.colors.length ? undefined : "sidecar");
  const defaultTheme = parsed.tokenTree?.themes?.default;
  const aliases = parsed.tokenTree?.aliases ?? {};
  const roleNames = {
    bg: [aliases.background, "bg", "background"],
    surface: ["surface"],
    text: [aliases.foreground, "text", "fg", "foreground"],
    accent: [aliases.accent, "accent"],
    accent2: ["accent-2"],
    divider: ["divider"],
  };
  for (const [role, candidates] of Object.entries(roleNames)) {
    const value = candidates.filter((name) => typeof name === "string").map((name) =>
      (defaultTheme && byPath.get(`colors.${defaultTheme}.${name}`)) || byPath.get(`colors.${name}`))
      .find((token) => token && token.source !== "markdown");
    if (value) m.colors.roles[role] = value.value;
    record(`colors.roles.${role}`, value, value?.source);
  }
  if (!Object.values(m.colors.roles).some(Boolean)) open.push("colors.roles");
  m.colors.ground = m.colors.roles.bg;
  m.colors.text = m.colors.roles.text;
  m.colors.accent = m.colors.roles.accent;
  open.push("colors.ramps", "colors.usage");

  const fontTokens = grouped("font").filter(({ path }) => path.startsWith("typography."));
  const extraFonts = fontTokens.filter(({ source }) => source === "sidecar");
  m.typography.list = [...parsed.fonts, ...new Set(extraFonts.map(({ value }) => value).filter((value) => !parsed.fonts.includes(value)))];
  const fontRoles = Object.fromEntries(fontTokens.map(({ path, value }) => [path.split(".").slice(1, -1).join("."), value]));
  if (parsed.typography?.families || fontTokens.length) m.typography.families = { ...fontRoles, ...parsed.typography?.families };
  if (parsed.typography?.weights?.length) m.typography.weights = parsed.typography.weights;
  const scale = grouped("fontSize").filter(({ path }) => path.startsWith("typography."));
  m.typography.scale = parsed.typography?.scale?.length ? parsed.typography.scale : scale.map(({ value }) => value);
  m.typography.heading.family = m.typography.families?.heading || m.typography.families?.display || "";
  m.typography.body.family = m.typography.families?.body || m.typography.families?.primary || "";
  record("typography.list", m.typography.list.length, parsed.fonts.length ? undefined : "sidecar");
  record("typography.scale", m.typography.scale.length, !parsed.typography?.scale?.length && scale.every(({ source }) => source === "sidecar") ? "sidecar" : undefined);
  record("typography.families", Object.keys(m.typography.families ?? {}).length);
  record("typography.weights", m.typography.weights?.length);

  const spacing = grouped("spacing");
  m.spacing.scale = tokenRows(spacing);
  record("spacing.scale", spacing.length, spacing.every(({ source }) => source === "sidecar") ? "sidecar" : undefined);
  for (const [group, path] of [["radius", "rounded"], ["shadows", "shadows"]]) {
    for (const key of Object.keys(m[group])) {
      const token = byPath.get(`${path}.${key}`) || byPath.get(`${group}.${key}`);
      if (token) m[group][key] = token.value;
      record(`${group}.${key}`, token, token?.source);
    }
  }
  const shadows = grouped("shadow");
  if (shadows.length) m.shadows.tokens = tokenRows(shadows);
  record("shadows.tokens", shadows.length, shadows.every(({ source }) => source === "sidecar") ? "sidecar" : undefined);

  open.push("components.classes", "assets", "starterTemplates");
  m.tokens.all = tokens.map(({ name, ...token }) => ({ name: name ?? token.path, ...token }));
  record("tokens.all", tokens.length);
  m.theme.params = {
    parsedFrom: "design-md",
    format: parsed.format,
    ...(parsed.frontmatter?.source_url ? { sourceUrl: parsed.frontmatter.source_url } : {}),
  };
  m.provenance = {
    parsedFrom: "design-md",
    format: parsed.format,
    enriched: sidecar.length > 0,
    filled,
    open,
    diagnostics: parsed.diagnostics,
  };
  return m;
}
